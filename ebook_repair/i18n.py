def pick(flag=None):
    for v in (flag, os.environ.get('EBOOK_REPAIR_LANG')):
        v = (v or '').lower()
        if v.startswith(('en', 'ru')):
            return v[:2]
    loc = os.environ.get('LC_ALL') or os.environ.get('LANG') or ''
    return 'ru' if loc.lower().startswith('ru') else 'en'


def t(key, **kw):
    return M[key][LANG == 'ru'].format(**kw)
